package dev.agentkeyboard.core.charart

import java.text.Normalizer
import java.util.Locale

/**
 * Big letters for the character art window (stage 53), like FIGlet fonts but drawn as pixels, so
 * every art style (braille, blocks, ASCII …) can draw them. Three small fonts of our own: [MINI]
 * (3×5), [STANDARD] (5×7) and [BOLD] (the standard font one pixel wider per stroke). Capitals,
 * digits, Ä Ö Ü, a few signs and ♥; other letters lose their accent (É → E), anything else is
 * drawn as "?" and reported.
 */
enum class BigFont(internal val height: Int, private val glyphs: Map<Char, List<String>>, private val bold: Boolean = false) {
    MINI(5, Glyphs.MINI),
    STANDARD(7, Glyphs.STANDARD),
    BOLD(7, Glyphs.STANDARD, bold = true);

    /** Pixels between letters and the width of a space. */
    internal val spacing: Int get() = 1
    private val spaceWidth: Int get() = if (this == MINI) 2 else 3

    /** One line of [text] in this font; [unsupported] is true if a character was drawn as "?". */
    class Line(val bits: Bits, val unsupported: Boolean)

    fun render(text: String): Line {
        val letters = prepare(text)
        var unsupported = false
        val pieces = letters.map { char ->
            if (char == ' ') Bits(spaceWidth, height)
            else glyph(char) ?: run { unsupported = true; glyph('?')!! }
        }
        if (pieces.isEmpty()) return Line(Bits(0, height), false)
        val width = pieces.sumOf { it.width } + spacing * (pieces.size - 1)
        val out = Bits(width, height)
        var left = 0
        for (piece in pieces) {
            for (y in 0 until piece.height) for (x in 0 until piece.width) if (piece[x, y]) out[left + x, y] = true
            left += piece.width + spacing
        }
        return Line(out, unsupported)
    }

    /** Width in pixels of [text] in this font. */
    fun width(text: String): Int = render(text).bits.width

    private fun glyph(char: Char): Bits? {
        val rows = glyphs[char] ?: return null
        val bits = Bits.parse(rows)
        if (!bold) return bits
        // a stroke one pixel wider to the right
        val out = Bits(bits.width + 1, bits.height)
        for (y in 0 until bits.height) for (x in 0 until bits.width) if (bits[x, y]) { out[x, y] = true; out[x + 1, y] = true }
        return out
    }

    private fun prepare(text: String): List<Char> {
        // the capital sharp s of the window's keys (ẞ) is drawn like ß in capitals: SS
        val upper = text.replace('❤', '♥').uppercase(Locale.GERMAN).replace("ẞ", "SS")
        val out = mutableListOf<Char>()
        for (char in upper) {
            if (char == '️' || char == '‍') continue // emoji variation, joiner
            if (char.isWhitespace()) { out += ' '; continue }
            if (glyphs.containsKey(char)) { out += char; continue }
            // a letter with an accent the font lacks: its base letter (É → E, Ñ → N)
            val base = Normalizer.normalize(char.toString(), Normalizer.Form.NFD).firstOrNull()
            out += if (base != null && glyphs.containsKey(base)) base else char
        }
        return out
    }
}

